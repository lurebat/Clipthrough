# Reproduces the whole UC8 evaluation. Every dotnet process runs at BelowNormal priority (dn.ps1).
# Output: fixtures/, results/*.json, run-log.txt. Scratch databases go to work/ and are deleted at the end.
param([switch]$NoBench, [switch]$KeepWork)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
Set-Location $root
$lines = [System.Collections.Generic.List[string]]::new()
function Log([string]$s) { $lines.Add($s); Write-Host $s }
function Dn([string[]]$a, [switch]$AllowFailure) {
    $out = & pwsh -NoProfile -File (Join-Path $root 'dn.ps1') @a
    $code = $LASTEXITCODE
    foreach ($l in $out) { Log "  $l" }
    if ($code -ne 0 -and -not $AllowFailure) { throw "dotnet $($a -join ' ') exited $code" }
    if ($AllowFailure) { return $code }
}
# Round-trip verify failures are recorded and reported at the end rather than thrown, so one
# regression still lets the other stacks run and run-log.txt be written - but the run exits non-zero.
$verifyFailures = [System.Collections.Generic.List[string]]::new()

Log "# UC8 run log - generated by run-all.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss zzz')"
Log "# host: $([System.Runtime.InteropServices.RuntimeInformation]::OSDescription), $([Environment]::ProcessorCount) logical CPUs, dotnet SDK $(& dotnet --version), pwsh $($PSVersionTable.PSVersion)"
Log "# NOTE: shared machine, all dotnet processes at BelowNormal priority - timings are indicative only."
Log ""

Log "## build (Release)"
foreach ($p in 'FixtureGen', 'Harness3mc', 'HarnessE3mc211') {
    Dn @('build', "$p\$p.csproj", '--nologo', '-c', 'Release', '-verbosity:quiet')
}

Log ""
Log "## resolved packages (obj/project.assets.json)"
foreach ($p in 'FixtureGen', 'Harness3mc', 'HarnessE3mc211') {
    $libs = (Get-Content "$p\obj\project.assets.json" -Raw | ConvertFrom-Json).libraries.PSObject.Properties.Name -join ', '
    Log "  $p : $libs"
}

Log ""
Log "## A. fixtures generated with the CURRENT stack"
Dn @('FixtureGen\bin\Release\net10.0\FixtureGen.dll', 'gen', 'fixtures', 'work\gen')

$bench = if ($NoBench) { @('--no-bench') } else { @() }
$runs = @(
    @{ Tag = 'current-e_sqlcipher-2.1.11'; Dll = 'FixtureGen\bin\Release\net10.0\FixtureGen.dll'; Pre = @('harness'); Work = 'work\current' },
    @{ Tag = 'sqlite3mc-pclraw-2.6.1'; Dll = 'Harness3mc\bin\Release\net10.0\Harness3mc.dll'; Pre = @(); Work = 'work\mc3' },
    @{ Tag = 'e_sqlite3mc-2.1.11'; Dll = 'HarnessE3mc211\bin\Release\net10.0\HarnessE3mc211.dll'; Pre = @(); Work = 'work\e3mc' }
)
foreach ($r in $runs) {
    Log ""
    Log "## B. harness: $($r.Tag)"
    Dn (@($r.Dll) + $r.Pre + @('fixtures', $r.Work, 'results') + $bench)
    Log ""
    Log "## B.2 round trip: files written by $($r.Tag), re-opened (and written) by the CURRENT stack"
    $code = Dn @('FixtureGen\bin\Release\net10.0\FixtureGen.dll', 'verify', "results\$($r.Tag).roundtrip.json", "work\verify-$($r.Tag)", "results\$($r.Tag).roundtrip-verify.json") -AllowFailure
    if ($code -ne 0) { $verifyFailures.Add("$($r.Tag) (exit $code)") }
}

Log ""
Log "## package sizes (nupkg in the local NuGet cache) and win-x64 native binary"
$cache = (Get-Content 'Harness3mc\obj\project.assets.json' -Raw | ConvertFrom-Json).packageFolders.PSObject.Properties.Name | Select-Object -First 1
foreach ($pv in 'sqlitepclraw.bundle_e_sqlcipher/2.1.11', 'sqlitepclraw.lib.e_sqlcipher/2.1.11', 'sqlitepclraw.provider.e_sqlcipher/2.1.11',
    'sqlite3mc.pclraw.bundle/2.6.1', 'sqlite3mc.pclraw.lib/2.6.1', 'sqlite3mc.pclraw.provider/2.6.1', 'sqlitepclraw.core/3.0.2', 'sqlitepclraw.core/2.1.12',
    'sqlitepclraw.bundle_e_sqlite3mc/2.1.11', 'sqlitepclraw.lib.e_sqlite3mc/2.1.11') {
    $id, $v = $pv -split '/'
    $nupkg = Join-Path $cache "$id\$v\$id.$v.nupkg"
    $size = if (Test-Path $nupkg) { (Get-Item $nupkg).Length } else { 'n/a' }
    $rids = if (Test-Path (Join-Path $cache "$id\$v\runtimes")) { (Get-ChildItem (Join-Path $cache "$id\$v\runtimes") -Directory | ForEach-Object Name | Sort-Object) -join ',' } else { '-' }
    Log ("  {0,-45} nupkg={1,10} bytes  runtimes=[{2}]" -f "$id $v", $size, $rids)
}
foreach ($n in 'FixtureGen\bin\Release\net10.0\runtimes\win-x64\native\e_sqlcipher.dll', 'Harness3mc\bin\Release\net10.0\runtimes\win-x64\native\sqlite3mc.dll', 'HarnessE3mc211\bin\Release\net10.0\runtimes\win-x64\native\e_sqlite3mc.dll') {
    if (Test-Path $n) { Log ("  win-x64 native: {0} = {1} bytes" -f $n, (Get-Item $n).Length) }
}

Log ""
Log "## summary of check statuses"
foreach ($r in $runs) {
    $checks = Get-Content "results\$($r.Tag).checks.json" -Raw | ConvertFrom-Json
    $rt = Get-Content "results\$($r.Tag).roundtrip-verify.json" -Raw | ConvertFrom-Json
    $all = @($checks) + @($rt)
    $by = $all | Group-Object Status | ForEach-Object { "$($_.Name)=$($_.Count)" }
    Log "  $($r.Tag): $($by -join ' ')"
}

if (-not $KeepWork) { Remove-Item -Recurse -Force (Join-Path $root 'work') -ErrorAction SilentlyContinue }
if ($verifyFailures.Count -gt 0) {
    Log ""
    Log "## RESULT: round-trip verify FAILED for $($verifyFailures -join ', ')"
}
[System.IO.File]::WriteAllText((Join-Path $root 'run-log.txt'), (($lines -join "`n") + "`n"), [System.Text.UTF8Encoding]::new($false))
if ($verifyFailures.Count -gt 0) { exit 1 }
